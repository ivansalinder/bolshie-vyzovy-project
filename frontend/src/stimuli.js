function shuffleArray(arr) {
  const copy = [...arr]
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

/**
 * Случайно выбирает по `perComponent` заданий из каждого из 5 компонентов (по 20% каждого типа)
 * и перемешивает их так, чтобы два задания одного типа никогда не шли подряд.
 */
export function buildRandomizedStimuli(perComponent) {
  const buckets = new Map()
  for (const item of SENTENCE_STIMULI) {
    if (!buckets.has(item.component)) {
      buckets.set(item.component, [])
    }
    buckets.get(item.component).push(item)
  }

  const queues = []
  for (const [component, items] of buckets.entries()) {
    const selected = shuffleArray(items).slice(0, perComponent)
    if (selected.length > 0) {
      queues.push({ component, items: selected })
    }
  }

  const result = []
  let lastComponent = null

  while (queues.some((q) => q.items.length > 0)) {
    const active = queues.filter((q) => q.items.length > 0)
    const totalLeft = active.reduce((sum, q) => sum + q.items.length, 0)

    const mustPick = active.find(
      (q) => q.component !== lastComponent && q.items.length * 2 > totalLeft
    )

    let chosenQueue
    if (mustPick) {
      chosenQueue = mustPick
    } else {
      const candidates = active.filter((q) => q.component !== lastComponent)
      chosenQueue = candidates[Math.floor(Math.random() * candidates.length)]
    }

    result.push(chosenQueue.items.pop())
    lastComponent = chosenQueue.component
  }

  return result
}

